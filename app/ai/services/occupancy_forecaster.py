"""
app/ai/services/occupancy_forecaster.py
--------------------------------------------
Hostel Occupancy Prediction.

Loads the RandomForestRegressor trained by ml/train_occupancy_model.py
on the synthetic historical dataset, then projects it forward from
"today" for the requested number of days.

To keep forecasts grounded in reality rather than purely synthetic
history, predictions are anchored to the hostel's *actual current*
occupancy rate (computed live from the existing Room model via
app/reports' same aggregation approach) — the synthetic model supplies
the *shape* of the trend (seasonality, weekly pattern), and we rescale
it so day 0 of the forecast lines up with today's real occupancy.
"""

import math
from datetime import date, timedelta

import numpy as np
import pandas as pd

from app.extensions import db
from app.models import Room
from app.ai.services.model_loader import load_model
from sqlalchemy import func

MODEL_FILE = "occupancy_model.joblib"
META_FILE = "occupancy_model_meta.joblib"

MAX_FORECAST_DAYS = 180


def _current_actual_occupancy_percent() -> float:
    total_capacity = db.session.query(func.coalesce(func.sum(Room.capacity), 0)).scalar()
    total_occupied = db.session.query(func.coalesce(func.sum(Room.occupied_beds), 0)).scalar()
    if not total_capacity:
        return 0.0
    return round((total_occupied / total_capacity) * 100, 2)


def _engineer_row(trend_index: int, target_date: date) -> list:
    day_of_week = target_date.weekday()
    day_of_year = target_date.timetuple().tm_yday
    return [
        trend_index,
        day_of_week,
        math.sin((day_of_year / 365.0) * 2 * math.pi),
        math.cos((day_of_year / 365.0) * 2 * math.pi),
    ]


def forecast_occupancy(days: int = 30) -> dict:
    """
    Returns:
        {
            "forecast": [{"date": "2026-08-09", "predicted_occupancy_percent": 61.4}, ...],
            "current_occupancy_percent": 58.0,
            "source": "model" | "fallback",
            "disclaimer": "..."
        }
    """
    days = max(1, min(int(days), MAX_FORECAST_DAYS))
    current_occupancy = _current_actual_occupancy_percent()

    model = load_model(MODEL_FILE)
    meta = load_model(META_FILE)

    disclaimer = (
        "This forecast is generated by a machine learning model trained on "
        "synthetic demo data and anchored to today's real occupancy. Treat it "
        "as a planning aid, not a guaranteed outcome."
    )

    if model is None or meta is None:
        # Fallback: flat projection at current occupancy with a mild synthetic
        # weekly wave, so the endpoint still returns something useful even if
        # the model artifact hasn't been trained/generated yet.
        forecast = []
        for i in range(1, days + 1):
            target_date = date.today() + timedelta(days=i)
            wave = 3 * math.sin((i / 7.0) * 2 * math.pi)
            forecast.append({
                "date": target_date.isoformat(),
                "predicted_occupancy_percent": round(max(0.0, min(100.0, current_occupancy + wave)), 1),
            })
        return {
            "forecast": forecast,
            "current_occupancy_percent": current_occupancy,
            "source": "fallback",
            "disclaimer": disclaimer,
        }

    last_trend_index = meta["last_trend_index"]
    rows = []
    dates = []
    for i in range(1, days + 1):
        trend_index = last_trend_index + i
        target_date = date.today() + timedelta(days=i)
        rows.append(_engineer_row(trend_index, target_date))
        dates.append(target_date)

    feature_df = pd.DataFrame(rows, columns=meta["feature_columns"])
    raw_predictions = model.predict(feature_df)

    # Anchor: shift the model's own day-1 prediction to match today's real
    # occupancy, then apply that same offset across the whole forecast so
    # the trend shape is preserved but the starting point is realistic.
    offset = current_occupancy - raw_predictions[0]
    adjusted = np.clip(raw_predictions + offset, 0, 100)

    forecast = [
        {"date": d.isoformat(), "predicted_occupancy_percent": round(float(v), 1)}
        for d, v in zip(dates, adjusted)
    ]

    return {
        "forecast": forecast,
        "current_occupancy_percent": current_occupancy,
        "source": "model",
        "disclaimer": disclaimer,
    }
